#!/usr/bin/env node
'use strict'

/**
 * Regenerates design/tokens.css from design/tokens.json (no dependencies).
 *   node design/build-tokens.js           write design/tokens.css
 *   node design/build-tokens.js --check   exit 1 if tokens.css is stale
 * Light is the default; dark applies only under :root[data-theme="dark"].
 * There is intentionally NO prefers-color-scheme auto-dark.
 */
const fs = require('fs')
const path = require('path')

const TOKENS = path.join(__dirname, 'tokens.json')
const OUT = path.join(__dirname, 'tokens.css')

// token group path -> CSS custom property prefix
const GROUPS = [
  ['font.family', '--k-font-'],
  ['font.size', '--k-text-'],
  ['font.weight', '--k-weight-'],
  ['font.tracking', '--k-tracking-'],
  ['font.leading', '--k-leading-'],
  ['space', '--k-space-'],
  ['radius', '--k-radius-'],
  ['shadow', '--k-shadow-'],
  ['layout', '--k-layout-'],
  ['z', '--k-z-']
]
const MOTION = [
  ['motion.duration', '--k-dur-'],
  ['motion.easing', '--k-ease-']
]

function load () { return JSON.parse(fs.readFileSync(TOKENS, 'utf8')) }

function get (obj, dotted) { return dotted.split('.').reduce((o, k) => (o ? o[k] : undefined), obj) }

/** leaf tokens of a group as [name, value]; skips $-prefixed metadata */
function leaves (group) {
  return Object.keys(group || {})
    .filter(k => !k.startsWith('$'))
    .map(k => [k, group[k].$value])
}

function decls (pairs, prefix) {
  return pairs.map(([k, v]) => `  ${prefix}${k}: ${v};`)
}

function buildCss (tokens) {
  const colorDecls = mode => decls(leaves(tokens.color[mode]), '--k-color-')
  const base = []
  for (const [grp, prefix] of GROUPS) base.push(...decls(leaves(get(tokens, grp)), prefix))
  const motion = []
  for (const [grp, prefix] of MOTION) motion.push(...decls(leaves(get(tokens, grp)), prefix))
  const durationReset = leaves(get(tokens, 'motion.duration')).map(([k]) => `    --k-dur-${k}: 0.01ms;`)

  return [
    '/* GENERATED by design/build-tokens.js from design/tokens.json. Do not edit by hand. */',
    '/* Light is the default. Dark only under [data-theme="dark"]; never switched by the OS setting. */',
    ':root {',
    '  color-scheme: light;',
    ...colorDecls('light'),
    ...base,
    ...motion,
    '}',
    '',
    ':root[data-theme="dark"] {',
    '  color-scheme: dark;',
    ...colorDecls('dark'),
    '}',
    '',
    '/* Safety net: collapse all token durations for users who ask for reduced motion. */',
    '/* Patterns must still avoid movement inside @media (prefers-reduced-motion: no-preference). */',
    '@media (prefers-reduced-motion: reduce) {',
    '  :root {',
    ...durationReset,
    '  }',
    '}',
    ''
  ].join('\n')
}

// ---- WCAG contrast helpers (shared with tokens.test.js) -------------------
function hexToRgb (hex) {
  const m = /^#([0-9a-f]{6})$/i.exec(hex)
  if (!m) throw new Error(`not a #RRGGBB colour: ${hex}`)
  const n = parseInt(m[1], 16)
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}
function luminance (hex) {
  const [r, g, b] = hexToRgb(hex).map(v => {
    const c = v / 255
    return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4)
  })
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
function contrast (a, b) {
  const x = luminance(a)
  const y = luminance(b)
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05)
}

function main () {
  const css = buildCss(load())
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').split('\r\n').join('\n') : ''
    if (cur !== css) { console.error('design/tokens.css is stale: run node design/build-tokens.js'); process.exit(1) }
    console.log('design/tokens.css is up to date')
    return
  }
  fs.writeFileSync(OUT, css)
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`)
}

if (require.main === module) main()

module.exports = { load, buildCss, contrast, luminance, hexToRgb, leaves, OUT }
